#!/usr/bin/env python3
"""Render the curated construction catalogue against current accepted records."""
import argparse
import hashlib
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "site/dist"
SOURCE = DIST / "data/constructions.json"
OUTPUT = DIST / "constructions.html"
GITHUB = "https://github.com/sebastienpalcoux/grothendieck-ring-classification/blob/main/"


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def escape(value):
    return html.escape(str(value), quote=True)


def asset(name):
    digest = hashlib.sha256((DIST / name).read_bytes()).hexdigest()[:12]
    return f"./{name}?v={digest}"


def render():
    data = read_json(SOURCE)
    assert data["schema"] == "construction-shortlist/v1"
    models = read_json(DIST / "data/realized_rings.json")["records"]
    for filename in ("rank9_rank10_m1.json", "rank11_m1.json", "rank9_m2.json"):
        models += [r for r in read_json(DIST / "data" / filename)["cases"]
                   if r.get("status") in ("realized", "unitarily_realized")]
    records = {r["id"]: r for r in models}
    flags = read_json(DIST / "data/ring_property_flags.json")["records"]
    entries = data["entries"]
    assert len({e["id"] for e in entries}) == len(entries), "Duplicate construction ID"
    key = lambda e: tuple(map(int, re.fullmatch(r"R(\d+)_(\d+)_(\d+)", e["id"]).groups()))
    entries = sorted(entries, key=key)
    cards = []
    for entry in entries:
        identifier = entry["id"]
        rank, multiplicity, _ = key(entry)
        record = records[identifier]
        assert record["existence"] in ("unitary", "realized", "unitarily_realized"), identifier
        assert (record["rank"], record["multiplicity"]) == (rank, multiplicity), identifier
        assert flags[identifier]["tensor_sha256"] == record["tensor_sha256"], identifier
        props = flags[identifier]["properties"]
        assert len(props) == 8 and all(type(v) is bool for v in props.values()), identifier
        source = (ROOT / entry["source"]).resolve()
        assert source.is_relative_to(ROOT) and source.is_file(), entry["source"]
        search = " ".join(entry[field] for field in ("title", "construction", "inputs"))
        cards.append(f'''      <article class="construction-entry" id="{identifier}" data-id="{identifier}" data-rank="{rank}" data-multiplicity="{multiplicity}" data-search="{escape(search)}" data-properties="{escape(json.dumps(props, separators=(',', ':')))}" aria-labelledby="title-{identifier}">
        <p class="construction-meta"><a href="#{identifier}" aria-label="Link to {identifier}">{identifier}</a><span>Rank {rank}</span><span>Multiplicity {multiplicity}</span></p>
        <h2 id="title-{identifier}">{escape(entry['title'])}</h2>
        <p class="construction-description">{escape(entry['construction'])}</p>
        <p class="construction-inputs"><strong>Ingredients and context.</strong> {escape(entry['inputs'])}</p>
        <div class="construction-links"><a href="./case.html?rank={rank}&amp;m={multiplicity}&amp;id={identifier}">Complete case record →</a><a href="{escape(GITHUB + entry['source'])}">{escape(entry['source_label'])} ↗</a></div>
      </article>''')
    options = "".join(f'<option value="{r}">{r}</option>' for r in sorted({key(e)[0] for e in entries}))
    return f'''<!doctype html>
<!-- Generated by site/build_constructions.py from the curated shortlist and current records. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#0d1325">
  <meta name="description" content="Documented constructions whose specific form has not, to our knowledge, been explicitly recorded in the literature. No claim of novelty up to tensor equivalence or of exoticness.">
  <title>“New” constructions · Fusion &amp; Grothendieck Ring Atlas</title>
  <link rel="canonical" href="https://sebastienpalcoux.github.io/grothendieck-ring-classification/constructions.html">
  <link rel="stylesheet" href="{asset('styles.css')}">
  <link rel="stylesheet" href="{asset('cases.css')}">
  <link rel="stylesheet" href="{asset('constructions.css')}">
  <script src="{asset('properties.js')}" defer></script>
  <script src="{asset('constructions.js')}" defer></script>
</head>
<body>
  <a class="skip-link" href="#construction-main">Skip to the constructions catalogue</a>
  <header class="site-header">
    <a class="brand" href="./index.html" aria-label="Fusion and Grothendieck Ring Atlas home"><span class="brand-symbol" aria-hidden="true"><span>FG</span></span><span class="brand-name">FUSION &amp; GROTHENDIECK<span class="brand-sub">RING ATLAS</span></span></a>
    <nav class="top-nav" aria-label="Main navigation"><a href="./index.html#atlas">Explore</a><a href="./records.html">Case records</a><a href="./constructions.html" class="nav-active" aria-current="page">Constructions</a><a href="./unresolved.html">Unresolved cases</a><a href="./index.html#papers">Papers</a><a href="./theory.html">Theory &amp; definitions</a></nav>
  </header>
  <main id="construction-main">
    <section class="case-hero"><p class="eyebrow">RING ATLAS / CONSTRUCTIONS CATALOGUE</p><h1>“New” <em>constructions</em></h1><p class="case-hero-description">Specific constructions, their known ingredients, and the proofs that identify their census rings.</p></section>
    <section class="case-content-section" aria-label="Documented construction examples">
      <aside class="construction-scope" aria-labelledby="meaning-of-new">
        <h2 id="meaning-of-new">What does “new” mean here?</h2>
        <p>{escape(data['meaning'])}</p>
      </aside>
      <form class="construction-toolbar" role="search" aria-label="Filter construction examples">
        <div><label for="construction-search">Find a construction</label><input id="construction-search" type="search" placeholder="Identifier, construction or ingredient"></div>
        <div><label for="construction-rank">Rank</label><select id="construction-rank"><option value="">All ranks</option>{options}</select></div>
        <div><label for="construction-m">Exact multiplicity</label><input id="construction-m" type="number" min="1" step="1" placeholder="Any"></div>
        <button id="construction-reset" type="button" disabled>Clear filters</button>
      </form>
      <div id="construction-property-filters"></div>
      <p id="construction-count" aria-live="polite">{len(entries)} examples · ordered by rank, multiplicity and identifier</p>
      <p id="construction-empty" hidden>No constructions match these filters. Clear the filters to see all examples.</p>
      <noscript><p>All entries appear below. Filtering requires JavaScript.</p></noscript>
      <div class="construction-list">
{chr(10).join(cards)}
      </div>
    </section>
  </main>
  <footer class="site-footer"><div class="footer-main"><span class="footer-brand">FUSION &amp; GROTHENDIECK RING ATLAS</span><a href="./index.html">Research atlas ↑</a><a href="https://github.com/sebastienpalcoux/grothendieck-ring-classification">GitHub source ↗</a></div><p class="footer-caution">AI-generated research · Independent human verification and Lean formalization pending. <a href="./review.html">Research status &amp; verification</a></p></footer>
</body>
</html>
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the committed page without writing it")
    args = parser.parse_args()
    output = render()
    if args.check:
        assert OUTPUT.read_text(encoding="utf-8") == output, "Rebuild with python site/build_constructions.py"
        print("Construction catalogue: curated IDs, accepted models, tensor-bound properties, sources and generated page verified")
    else:
        OUTPUT.write_text(output, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")
