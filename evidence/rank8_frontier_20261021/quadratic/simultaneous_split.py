"""Exact simultaneous C2 split-module obstruction; default is read-only replay.

The finite search uses Python integer matrix arithmetic.  The quotient and
interpolation are computed over QQ by SymPy.  No solver tolerance, floating
point, resource cutoff, or assertion is used in an exclusion.
"""
from pathlib import Path
import argparse
import hashlib
import itertools
import json
import math
import sympy as sp

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / 'rank8_m3_20261021/pipeline/census_m3.json'
TARGETS = [1203, 1350, 2842, 2885]


def require(condition, message):
    if not condition:
        raise ValueError(message)


def identity(n):
    return [[int(i == j) for j in range(n)] for i in range(n)]


def zero(n):
    return [[0] * n for _ in range(n)]


def multiply(A, B):
    n = len(A)
    return [[sum(A[i][k] * B[k][j] for k in range(n))
             for j in range(n)] for i in range(n)]


def polynomial(A, coefficients):
    n = len(A)
    V = zero(n)
    for c in coefficients:
        V = multiply(V, A)
        for i in range(n):
            V[i][i] += c
    return V


def source_rows():
    return {r['id']: r for r in json.loads(SOURCE.read_text())}


def fingerprint(R):
    return hashlib.sha256(json.dumps(R, separators=(',', ':')).encode()).hexdigest()


def setup(R, g, x):
    n = len(R)
    require(n == 8, 'rank must be eight')
    require(all(R[i][j] == R[j][i] for i, j in itertools.product(range(n), repeat=2)),
            'commutativity required')
    require(g != 0 and R[g][g] == [1] + [0] * (n - 1), 'order-two invertible required')
    require(R[x][x][0] == 1, 'self-dual generator required')
    action = [next(j for j in range(n) if R[g][i][j]) for i in range(n)]
    require(all(R[g][i] == [int(j == action[i]) for j in range(n)] for i in range(n)),
            'invertible action not a permutation')
    fixed = [i for i in range(n) if action[i] == i]
    require(fixed, 'fixed object needed to trivialize pointed associator')
    odd = []
    for v in fixed:
        candidates = [a for a in fixed if R[a][v][v] % 2]
        require(candidates, 'odd fixed-generator diagonal coverage failed')
        odd.append([v, candidates[0], R[candidates[0]][v][v]])
    orbits = []
    for i in range(n):
        if not any(i in o for o in orbits):
            orbits.append(sorted({i, action[i]}))
    q = len(orbits)
    Q = [sp.Matrix([[sum(R[a][o[0]][j] for j in oo) for oo in orbits]
                    for o in orbits]) for a in range(n)]
    # A faithful regular representation of R_Q/(g-1), checked directly.
    require(Q[0] == sp.eye(q) and Q[g] == sp.eye(q), 'quotient unit failed')
    require(all(Q[i] * Q[j] == sum((R[i][j][k] * Q[k] for k in range(n)), sp.zeros(q))
                for i, j in itertools.product(range(n), repeat=2)), 'quotient multiplication failed')
    powers = [Q[x] ** k for k in range(q)]
    span = sp.Matrix.hstack(*(A.reshape(q * q, 1) for A in powers))
    require(span.rank() == q, 'quotient is not generated by selected object')
    interpolation = []
    for a in range(n):
        solution, parameters = span.gauss_jordan_solve(Q[a].reshape(q * q, 1))
        require(parameters.rows == 0, 'nonunique quotient interpolation')
        den = int(sp.ilcm(*(v.q for v in solution)))
        nums = [int(v * den) for v in solution]
        require(sum((c * A for c, A in zip(nums, powers)), sp.zeros(q)) == den * Q[a],
                'interpolation identity failed')
        interpolation.append({'denominator': den, 'ascending_numerators': nums})
    p = [int(c) for c in Q[x].charpoly().all_coeffs()]
    require(polynomial(Q[x].tolist(), p) == zero(q), 'source polynomial failed')
    f = len(fixed)
    bounds = [[R[x][v][w] for w in fixed] for v in fixed]
    require(bounds == list(map(list, zip(*bounds))), 'generator fixed block not symmetric')
    parent = list(range(f))

    def root(i):
        while parent[i] != i:
            i = parent[i]
        return i

    entries = []
    for i in range(f):
        for j in range(i, f):
            b = bounds[i][j]
            choices = list(range(-b, b + 1, 2))
            gauge = i != j and b % 2 and root(i) != root(j)
            if gauge:
                parent[root(i)] = root(j)
                choices = [a for a in choices if a > 0]
            entries.append([i, j, choices, bool(gauge)])
    return {'involution': g, 'generator': x, 'fixed': fixed,
            'odd_diagonal_witnesses': odd, 'quotient_orbits': orbits,
            'quotient_polynomial': p, 'interpolation': interpolation,
            'bounds': bounds, 'entries': entries,
            'finite_cases': math.prod(len(e[2]) for e in entries)}


def reject_or_reconstruct(R, a, B):
    f = len(B)
    powers = [identity(f)]
    for _ in range(1, len(a['quotient_orbits'])):
        powers.append(multiply(powers[-1], B))
    matrices = []
    for x, interpolation in enumerate(a['interpolation']):
        den = interpolation['denominator']
        nums = interpolation['ascending_numerators']
        matrix = zero(f)
        for i, v in enumerate(a['fixed']):
            for j, w in enumerate(a['fixed']):
                num = sum(c * P[i][j] for c, P in zip(nums, powers))
                if num % den:
                    return {'basis_index': x, 'row': i, 'column': j,
                            'reason': 'nonintegral', 'numerator': num, 'denominator': den}
                z = num // den
                b = R[x][v][w]
                if abs(z) > b or (z - b) % 2:
                    return {'basis_index': x, 'row': i, 'column': j,
                            'reason': 'bound_or_parity', 'entry': z, 'bound': b}
                matrix[i][j] = z
        matrices.append(matrix)
    # A surviving exact system must satisfy all multiplication and duality.
    verify_system(R, a['fixed'], matrices)
    return {'reason': 'exact_bounded_representation', 'matrices': matrices}


def verify_system(R, fixed, matrices):
    n, f = len(R), len(fixed)
    require(matrices[0] == identity(f), 'module identity failed')
    dual = [next(j for j in range(n) if R[i][j][0]) for i in range(n)]
    for x in range(n):
        require(matrices[dual[x]] == list(map(list, zip(*matrices[x]))), 'module duality failed')
        for i, v in enumerate(fixed):
            for j, w in enumerate(fixed):
                z, b = matrices[x][i][j], R[x][v][w]
                require(isinstance(z, int) and abs(z) <= b and (z - b) % 2 == 0,
                        'module entry bound/parity failed')
    for x, y in itertools.product(range(n), repeat=2):
        product = multiply(matrices[x], matrices[y])
        expected = [[sum(R[x][y][z] * matrices[z][i][j] for z in range(n))
                     for j in range(f)] for i in range(f)]
        require(product == expected, 'module multiplication failed')


def search(R, g, x):
    a = setup(R, g, x)
    f = len(a['fixed'])
    candidates = []
    tested = 0
    for values in itertools.product(*(e[2] for e in a['entries'])):
        B = zero(f)
        for z, (i, j, _, _) in zip(values, a['entries']):
            B[i][j] = B[j][i] = z
        tested += 1
        if polynomial(B, a['quotient_polynomial']) != zero(f):
            continue
        candidates.append({'matrix': B, 'reconstruction': reject_or_reconstruct(R, a, B)})
    require(tested == a['finite_cases'], 'finite domain not exhausted')
    return {'setup': a, 'tested': tested, 'polynomial_survivors': candidates,
            'outcome': 'no_conclusion' if any(c['reconstruction']['reason'] ==
                         'exact_bounded_representation' for c in candidates) else 'excluded'}


def report():
    rows = source_rows()
    output = []
    for index in TARGETS:
        row = rows[f'R8_3_{index}']
        R = row['tensor']
        require(fingerprint(R) == row['tensor_sha256'], 'source digest failed')
        g = 3 if index in (1203, 1350) else 1
        output.append({'id': row['id'], 'tensor_sha256': row['tensor_sha256'],
                       'scope': 'general_complex_fusion_category', 'search': search(R, g, 4)})
    control = rows['R8_3_342']
    matrices = [identity(2) for _ in range(8)]
    matrices[5] = [[-2, -1], [-1, 1]]
    matrices[6] = [[1, 1], [1, -2]]
    verify_system(control['tensor'], [5, 6], matrices)
    return {'criterion': 'simultaneous_C2_split_module_quotient', 'version': 1,
            'records': output,
            'positive_control': {'id': control['id'], 'tensor_sha256': fingerprint(control['tensor']),
                                 'known_model': 'Rep(C13 semidirect C6)', 'involution': 7,
                                 'fixed': [5, 6], 'exact_bounded_representation': matrices,
                                 'scope_note': 'Checks every simultaneous relation; the cyclic-self-dual quotient specialization is inapplicable to this control.'}}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    actual = report()
    target = HERE / 'simultaneous_split_results.json'
    if args.write:
        target.write_text(json.dumps(actual, indent=2) + '\n')
    else:
        require(actual == json.loads(target.read_text()), 'saved evidence does not replay')
    require(all(r['search']['outcome'] == 'excluded' for r in actual['records']), 'unexpected surviving system')
    print('PASS: 4 exact general-complex simultaneous split-module exclusions; positive control passes')
