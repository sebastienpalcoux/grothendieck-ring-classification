"""Verify the exact central extension used for baseline C2 module coherence.
D32 -> D16 restricts over its normal D8 to D16 -> D8; the Schur class
is nontrivial because the kernel lies in the commutator subgroup.
"""
import itertools,json
from pathlib import Path

def mul(n,x,y):return((x[0]+(-1)**x[1]*y[0])%n,x[1]^y[1])
def inv(n,x):return next(y for y in itertools.product(range(n),range(2))if mul(n,x,y)==(0,0))
Q=list(itertools.product(range(8),range(2)))
H=[x for x in Q if x[0]%2==0]
r=(2,0);s=(0,1);t=(7,1)
assert mul(8,t,t)==(0,0)
assert mul(8,mul(8,t,r),t)==inv(8,r)
assert mul(8,mul(8,t,s),t)==mul(8,s,r)
assert len(H)==8 and all(mul(8,mul(8,x,h),inv(8,x))in H for x in Q for h in H)
def coc(x,y):
 lifted=mul(16,x,y);plain=mul(8,x,y)
 assert lifted[1]==plain[1]and(lifted[0]-plain[0])%8==0
 return ((lifted[0]-plain[0])//8)%2
assert all((coc(y,z)-coc(mul(8,x,y),z)+coc(x,mul(8,y,z))-coc(x,y))%2==0 for x,y,z in itertools.product(Q,repeat=3))
assert coc(t,t)==0
# The preimage of H is generated by R=(2,0) and S=(0,1) in D32.
# R has order8 and S R S=R^-1, so it is D16. Its central kernel isR^4.
R=(2,0);S=(0,1);kernel=(8,0)
def power(n,x,k):
 y=(0,0)
 for _ in range(k):y=mul(n,y,x)
 return y
assert power(16,R,4)==kernel and power(16,R,8)==(0,0)
comm=mul(16,mul(16,mul(16,R,S),inv(16,R)),inv(16,S))
assert power(16,comm,2)==kernel
# Hence every 1-dimensional representation of the covering D16 kills the
# kernel, so the kernel-odd projective Schur class on H is not a coboundary.
report={'status':'PASS','base_group':'D16','normal_subgroup':'D8','cover':'D32','restricted_cover':'D16','outer_generator':t,'outer_action':{'r':'r^-1','s':'s*r'},'cocycle_exponents':[[coc(x,y)for y in Q]for x in Q],'quotient_elements':Q,'subgroup_elements':H,'restriction_to_external_C2_trivial':True,'restricted_class_nontrivial':'kernel lies in commutator subgroup of covering D16'}
Path(__file__).with_name('triality_schur_extension.json').write_text(json.dumps(report,indent=2)+'\n')
print('PASS nontrivial D8 Schur class extends to D16; external C2 restriction trivial')
