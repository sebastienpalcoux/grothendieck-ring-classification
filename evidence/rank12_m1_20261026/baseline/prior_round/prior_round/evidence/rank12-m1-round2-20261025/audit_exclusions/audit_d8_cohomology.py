def rank2(M):
    A=np.array(M,dtype=np.uint8)%2;r=0
    for c in range(A.shape[1]):
        hits=np.flatnonzero(A[r:,c])
        if not len(hits):continue
        i=int(hits[0])+r;A[[i,r]]=A[[r,i]]
        for i in np.flatnonzero(A[r+1:,c])+r+1:A[i]^=A[r]
        r+=1
    return r

def split4(M,track=False):
    A=np.array(M,dtype=np.int64)%4;m,n=A.shape;U=np.eye(m,dtype=np.int64)if track else None;r=0
    while r<min(m,n):
        hits=np.argwhere(A[r:,r:]%2)
        if not len(hits):break
        i,j=map(int,hits[0]+r);A[[i,r]]=A[[r,i]];A[:,[j,r]]=A[:,[r,j]]
        if track:U[[i,r]]=U[[r,i]]
        v=int(A[r,r]);A[r]=A[r]*v%4
        if track:U[r]=U[r]*v%4
        col=A[:,r].copy();col[r]=0
        A=(A-col[:,None]*A[r])%4
        if track:U=(U-col[:,None]*U[r])%4
        r+=1
    require(not np.any(A[r:,r:]%2),'only even residual block')
    even=(A[r:,r:]//2).astype(np.uint8);r2=rank2(even)
    return r,r2,even,U

