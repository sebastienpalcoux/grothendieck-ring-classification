import json
import sys

HERE = Path(__file__).resolve().parent
SOURCE = (Path(sys.argv[1]) if len(sys.argv)>1 else
          HERE.parents[1]/'unresolved11_20261024/inputs/R10_1_189.json')
BRANCHES = [
    [(0,0,0),(0,6,0),(2,0,2),(2,2,2)],
    [(0,0,2),(2,4,0),(2,1,2)],
    [(0,1,2),(2,3,0),(3,0,3)],
    [(1,0,3),(3,2,1),(0,3,0)],
    [(0,0,4),(4,2,0),(1,2,1)],
    [(0,0,6),(6,0,0),(0,2,2),(2,2,0)],
    [(4,0,0),(0,2,4),(1,2,1)],
    [(3,0,1),(1,2,3),(0,3,0)],
    [(0,3,2),(2,1,0),(3,0,3)],
    [(2,0,0),(0,4,2),(2,1,2)],
]
P = [0,1,8,7,2,9,4,6,5,3]

def need(value, message):
    if not value:
        raise ValueError(message)

def exterior_two_pieri(weight):
    a,b,c=weight
    partition=[a+b+c,b+c,c,0]
    out=Counter()
    for rows in combinations(range(4),2):
        p=[v+int(i in rows) for i,v in enumerate(partition)]
        if any(p[i]<p[i+1] for i in range(3)):
            continue
        # A full column of height four is the trivial determinant of SU(4).
        out[tuple(p[i]-p[i+1] for i in range(3))]+=1
    return out

def product_by_v(character):
    out=Counter()
    for weight,m in character.items():
        for new,n in exterior_two_pieri(weight).items():
            out[new]+=m*n
    return out

def model_tensor():
    T=[]
    for i in range(10):
        row=[]
        for j in range(10):
            vec=[0]*10
            if i<5 and j<5:
                vec[(i+j)%5]=1
            elif min(i,j)<5:
                vec[5+(i+j)%5]=1
            else:
                vec[(i+j)%5]=1
                for h in range(1,5):
                    vec[5+(i+j+h)%5]=1
            row.append(vec)
        T.append(row)
    return T

def run():
    v=Counter({(0,1,0):1})
    v2=product_by_v(v)
    v3=product_by_v(v2)
    need(v2==Counter({(0,0,0):1,(0,2,0):1,(1,0,1):1}), 'Pieri square')
    need(v3==Counter({(0,1,0):3,(1,1,1):2,(0,3,0):1,(2,0,0):1,(0,0,2):1}), 'Pieri cube')
    need(max(sum(w) for w in v3)<=3<6, 'no affine truncation')
    need(all(sum(w)<=6 for b in BRANCHES for w in b), 'integrable branches')
    h2=[sum(v2[w] for w in b) for b in BRANCHES]
    h3=[sum(v3[w] for w in b) for b in BRANCHES]
    need(h2==[1]+[0]*9,'simple beta and distinct translates')
    need(h3==[int(j in [1,3,7,9]) for j in range(10)], 'beta square coefficients')
    need([(j-5)//2 %5 for j in [1,3,7,9]]==[3,4,1,2], 'g,x relabeling')
    # d=2+sqrt5: d²=9+4sqrt5=1+4d.
    need((2*2+5,2*2)==(1+4*2,4),'dimension exhaustion')
    profile=json.loads(SOURCE.read_text())
    source=profile['fusion_tensor'];T=model_tensor()
    digest=sha256(json.dumps(source,separators=(',',':')).encode()).hexdigest()
    need(digest==profile['tensor_sha256'],'source tensor binding')
    for i in range(10):
        for j in range(10):
            need([source[P[i]][P[j]][P[k]] for k in range(10)]==T[i][j],
                 f'census tensor mismatch at {i},{j}')
    receipt={
        'status':'PASS',
        'case':'R10_1_189',
        'classification':'unitarily categorified',
        'model':'fusion subcategory generated by tau_2 and tau_5 F(010) in SU(4)_6_B, B from SU(4)_6 subset SU(10)_1',
        'source_tensor_sha256':digest,
        'basis_permutation':P,
        'structure_constants_checked':1000,
        'square':{''.join(map(str,w)):n for w,n in sorted(v2.items())},
        'cube':{''.join(map(str,w)):n for w,n in sorted(v3.items())},
        'branching':BRANCHES,
        'simple_translate_intersections':h2,
        'square_multiplicities':h3,
        'FPdim_noninvertible':'2+sqrt(5)',
        'categorical_premise':'actual connected etale algebra of the cited conformal embedding; local category SU(10)_1',
        'primary_source':'Bockenhauer-Evans arXiv:math/0006114v2, p.29',
        'scope':'Finite checks supplement the categorical construction in CONFORMAL_MODEL.md; no modular-data existence assumption.'
    }
    (HERE/'conformal_model_certificate.json').write_text(json.dumps(receipt,indent=2)+'\n')
    print(json.dumps(receipt,indent=2))

if __name__=='__main__':
    run()
