#!/usr/bin/env python3
"""Generate TeX counts from the scope and a successful exact replay report."""


def _require(condition, message):
    if not condition:
        raise RuntimeError(message)

from pathlib import Path
from collections import Counter
import gzip, hashlib, json
ROOT=Path(__file__).resolve().parent
spec=json.loads((ROOT/'scope.json').read_text())
report=json.loads((ROOT/'verification/compact_summary.json').read_text())
global_report=report['global_catalog_report']
_require(report['bound']==spec['bound']==global_report['bound'], 'supplementary/classification/generate_scope.py exact check failed at source line 10')
_require(report['positive_catalog_coverage'] and report['unresolved']==0, 'supplementary/classification/generate_scope.py exact check failed at source line 11')
cert=ROOT/'data'/spec['certificate_file']
_require(hashlib.sha256(cert.read_bytes()).hexdigest()==report['certificate_sha256'], 'supplementary/classification/generate_scope.py exact check failed at source line 13')
with gzip.open(cert,'rt') as f:
    header=json.loads(next(f))
    counts=Counter(json.loads(line)['certificate']['kind'] for line in f)
_require(counts==Counter(report['top_level_criteria']), 'supplementary/classification/generate_scope.py exact check failed at source line 17')
_require(sum(counts.values())==report['checked_records']==header['records'], 'supplementary/classification/generate_scope.py exact check failed at source line 18')
values={'Bound':spec['bound'],'AllSigned':global_report['total_orbits'],
        'DnumberRejected':global_report['universal_dnumber_rejections'],
        'CyclotomicRejected':global_report['universal_cyclotomic_rejections'],
        'RetainedSigned':global_report['retained_orbits'],
        'PositiveRecords':report['checked_records'],
        'ExcludedRecords':report['excluded'],'SelfDualModels':report['realized']}
lines=['% Generated by supplementary/classification/generate_scope.py; do not edit counts by hand.']
for key,value in values.items():
    text=format(value,',').replace(',',r'\,')
    lines.append(r'\newcommand{\Verify'+key+'}{'+text+'}')
(ROOT/'generated_scope.tex').write_text('\n'.join(lines)+'\n')
justifications=[
 ('model','exact based isomorphism to a realized tensor'),
 ('rank_two_moment',r'Proposition~\ref{finite:prop:ranktwo}'),
 ('two_dimensions',r'\cite[Lemma~3.1]{Schopieray}, induction and moments'),
 ('diagonal_involution_moments',r'Theorem~\ref{finite:thm:diagonal}'),
 ('weak_integral','pseudo-unitarity, induction and moments'),
 ('automatic_spherical','proved sphericality, then a checked obstruction'),
 ('subring','fusion-subcategory dimension divisibility'),
 ('involution_propagation_42',r'Proposition~\ref{finite:prop:involution-propagation}'),
 ('signed','complete signed-table and character tests')]
_require(set(counts)=={k for k,_ in justifications}, 'supplementary/classification/generate_scope.py exact check failed at source line 40')
lines=[r'\begin{tabular}{lrl}',r'\toprule',
       r'Certificate type&Number&Mathematical justification\\',r'\midrule']
for key,why in justifications:
    lines.append(r'\texttt{'+key.replace('_',r'\_')+'}&'+str(counts[key])+'&'+why+r'\\')
lines += [r'\bottomrule',r'\end{tabular}']
(ROOT/'generated_criteria.tex').write_text('\n'.join(lines)+'\n')
print('Generated finite scope and criterion tables from verified data.')
