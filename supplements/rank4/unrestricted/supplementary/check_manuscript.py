#!/usr/bin/env python3
"""Verify census/ledger/model data and generate the two manuscript tables.

The model check recomputes all positive dimension characters, rather than
accepting numerical approximations or stored validity flags.
"""
from pathlib import Path
from collections import Counter
import argparse, csv, hashlib, json, sys
import sympy as s
ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT/'classification/software'))
from rings import validate, canonical
from exact import require


def load(p): return json.loads(p.read_text())
def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def number(n): return format(n, ',').replace(',', r'\,')


def dimension_tex(spec):
    if 'polynomial' in spec: return spec['symbol']
    a,b,c,k = [spec[v] for v in ['constant','coefficient','radicand','denominator']]
    require(all(type(v) is int for v in [a,b,c,k]) and min(a,b,c)>=0 and k>0,'radical specification')
    text = str(a)
    if b: text += '+' + ('' if b==1 else str(b)) + r'\sqrt{'+str(c)+'}'
    return '('+text+')/'+str(k) if k!=1 else text


def model_tex(meta):
    lines=[r'% Generated by supplementary/check_manuscript.py from verified model data.',
           r'\begin{table}[htbp]', r'\centering\small',
           r'\begin{tabular}{@{}clcl@{}}', r'\toprule',
           r'$\mu$ & A unitary realization & $D$ & Reference \\', r'\midrule']
    for row in meta:
        lines.append(f"${row['multiplicity']}$ & {row['name_tex']} & ${dimension_tex(row['dimension'])}$ & {row['reference_tex']} "+r'\\')
    lines += [r'\bottomrule',r'\end{tabular}',
              r'\caption{One unitary realization of each surviving based ring, with its',
              r'multiplicity $\mu$ and global Frobenius--Perron dimension $D$.',
              r"Here $D_{10}$ has order ten, $S'$ has index $3+2\sqrt2$, and the",
              r'near-group category of type $(C_3,3)$ is the Izumi--Xu category.}',
              r'\label{finite:tab:models}',r'\smallskip',r'\begin{minipage}{\textwidth}\footnotesize',
              r'The numbers $\delta_7$ and $\delta_E$ are the largest real roots of',
              r'$x^3-27x^2+162x-243$ and',r'$x^4-45x^3+375x^2-1125x+1125$, respectively.',
              r'The supplementary model check verifies these polynomials, the positive',
              r'dimension characters, and all tensor identifications exactly.',r'\end{minipage}',r'\end{table}']
    return '\n'.join(lines)+'\n'


def filters_tex(summary):
    lines=[r'% Generated by supplementary/check_manuscript.py from the checked ledger.',
           r'\begin{table}[htbp]',r'\centering\small',r'\begin{tabular}{@{}lrr@{}}',r'\toprule',
           r'Stage & Excluded & Remaining \\',r'\midrule',
           r'Complete census, $D<1000$ & --- & '+number(summary['census_count'])+r' \\']
    for row in summary['stages']:
        lines.append(row['title']+' & '+number(row['excluded'])+' & '+number(row['remaining'])+r' \\')
    lines += [r'\bottomrule',r'\end{tabular}',
              r'\caption{Successive exact filters for the complete ordinary fusion-ring',
              r'census. Each ring is counted once, at its recorded rejection stage.',
              r'The final stage covers every compatible signed quotient and every',
              r'character or induction-column choice required by its certificate.}',
              r'\label{finite:tab:filters}',r'\end{table}']
    return '\n'.join(lines)+'\n'


def run(write=False, manuscript_root=None):
    cm=load(ROOT/'census/data/manifest.json')
    summary=load(ROOT/'classification/results/summary.json')
    verification=load(ROOT/'classification/results/verification.json')
    require(verification['all_checks_passed'] and verification['fresh_signed_cover_in_this_run'],
            'a fresh complete classification replay is required')
    require(verification['census_sha256']==digest(ROOT/'census/data/rings.jsonl'),'stale census report')
    require(verification['ledger_sha256']==digest(ROOT/'classification/results/certificates.jsonl'),'stale ledger report')
    ledger=[json.loads(l) for l in (ROOT/'classification/results/certificates.jsonl').read_text().splitlines()]
    counted=Counter(r['stage'] for r in ledger)
    csv_rows=list(csv.DictReader((ROOT/'census/data/counts.csv').open()))
    total=sum(int(r['rings']) for r in csv_rows)
    require(total==cm['number_of_rings']==len(ledger)==summary['census_count']==verification['checked_rings'],
            'different census/ledger totals')
    remaining=total
    for row in summary['stages']:
        require(row['excluded']==counted[row['filter']],'incorrect stage count')
        remaining-=row['excluded'];require(remaining==row['remaining'],'incorrect running count')
    require(remaining==counted['model']==15,'survivor count')
    require(sum(int(r['self_dual']) for r in csv_rows)==cm['type_counts']['S'],'self-dual count')
    require(sum(int(r['one_dual_pair']) for r in csv_rows)==cm['type_counts']['N'],'dual-pair count')
    meta=load(ROOT/'model_table.json')
    models=load(ROOT/'classification/data/models.json')
    old={r['model']:r for r in load(ROOT/'classification/verification/exact_model_dimensions_audit.json')}
    independent=load(ROOT/'independent/results/models.json')
    require(independent['passed'] and independent['models']==15,'independent model reconstruction missing')
    require({r['archive_model'] for r in independent['rows']}=={m['model'] for m in models},'independent model identities')
    require(len(meta)==len(models)==len({canonical(m['matrices']) for m in models})==15,'model distinctness')
    model_results=[];x=s.Symbol('x');t=s.Symbol('t')
    for row,m in zip(meta,models):
        require(row['model']==m['model'],'model ordering')
        R=m['matrices'];validate(R);record=old[m['model']]
        ds=[s.sympify(v,locals={'t':t}) for v in record['fp_dimensions_in_model_basis']]
        require(all(d.is_positive is True for d in ds),'dimension positivity')
        ext=[d for d in ds if not d.is_Rational];K=s.QQ.algebraic_field(*ext) if ext else s.QQ
        v=[K.from_sympy(d) for d in ds]
        for i in range(4):
            for j in range(4):require(v[i]*v[j]==sum((R[i][j][k]*v[k] for k in range(4)),K.zero),'model character product')
        D=sum((d*d for d in v),K.zero)
        require(D==K.from_sympy(s.sympify(record['global_fp_dimension'],locals={'t':t})),'global dimension')
        spec=row['dimension']
        if 'polynomial' in spec:
            polynomial=s.Poly.from_list(spec['polynomial'],x,domain=s.QQ)
            value=K.zero
            for a in polynomial.all_coeffs():value=value*D+K.from_sympy(a)
            require(value==K.zero and polynomial.is_irreducible,'table polynomial')
            C=s.Matrix([[sum(R[i][j][l]*R[i][k][l] for i in range(4) for l in range(4)) for k in range(4)] for j in range(4)])
            cp=C.charpoly(x).as_poly()
            require(cp.rem(polynomial).is_zero,'table polynomial is not a Casimir factor')
            # Positive character proves D is the largest Casimir eigenvalue;
            # hence it is also the largest root of this factor.
        else:
            a,b,c,k=[spec[v] for v in ['constant','coefficient','radicand','denominator']]
            require(D==K.from_sympy((s.Integer(a)+b*s.sqrt(c))/k),'radical/table dimension')
        require(row['multiplicity']==max(z for A in R for rr in A for z in rr),'model multiplicity')
        model_results.append({'model':m['model'],'positive_character_checked':True,'table_dimension_checked':True})
    generated={ROOT.parent/'source/models.tex':model_tex(meta),
               ROOT.parent/'source/generated_filters.tex':filters_tex(summary)}
    macros={'Total':total,'SelfDual':cm['type_counts']['S'],'NonSelfDual':cm['type_counts']['N'],
            'Excluded':summary['excluded'],'Models':15}
    generated[ROOT.parent/'source/generated_census.tex']='% Generated from the local checked census.\n'+''.join(
        r'\newcommand{\Census'+k+'}{'+number(v)+'}\n' for k,v in macros.items())
    for path,text in generated.items():
        if write:path.write_text(text)
        else:require(path.read_text()==text,'stale generated manuscript data: '+str(path))
    if manuscript_root is not None:
        target=Path(manuscript_root).resolve()/'generated/unrestricted'
        for path,text in generated.items():
            require((target/path.name).read_text()==text,
                    'manuscript table differs from verified data: '+str(target/path.name))
        scope=ROOT/'classification/generated_scope.tex'
        require((target/scope.name).read_bytes()==scope.read_bytes(),
                'manuscript signed-scope counts differ from verified data')
        chart=ROOT.parent/'audit/quartic_trace13_table.tex'
        require((target/chart.name).read_bytes()==chart.read_bytes(),
                'manuscript quartic chart differs from the exact package')
    report={'passed':True,'census':total,'exclusions':summary['excluded'],'models':15,
            'stages':summary['stages'],'model_checks':model_results,
            'census_sha256':digest(ROOT/'census/data/rings.jsonl'),
            'ledger_sha256':digest(ROOT/'classification/results/certificates.jsonl'),
            'generated_files':{str(p.relative_to(ROOT.parent)):digest(p) for p in generated}}
    (ROOT/'validation/manuscript_data_check.json').write_text(json.dumps(report,indent=2)+'\n')
    print('PASS: census totals, successive filters, fifteen positive dimension characters, model-table dimensions, and generated TeX.',flush=True)
    return report


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write',action='store_true')
    parser.add_argument('--manuscript-root',type=Path,
                        help='also compare the companion paper generated/unrestricted tables')
    args=parser.parse_args();run(args.write,args.manuscript_root)
