#!/usr/bin/env python3
"""Generate an exact exclusion certificate for every non-model census ring.

No model comparison is made until all necessary-condition filters finish.
The input census is generated by census/generate.py and checked by census/verify_census.py.
"""
import argparse,json,multiprocessing,sys,time
from pathlib import Path
ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'software'))
import rapid
from rings import *
from literature import *
from spherical import *

def spherical_task(row):
    return row['id'],sphere_certificate(row['tensor'])

def arithmetic_task(row):
    a=Characters(row['tensor'])
    branches=[{'factor':pc(f),'obstruction':arithmetic_failure(a,f)} for f,m in a.components]
    if any(b['obstruction'] is None for b in branches):return row['id'],None
    return row['id'],{'kind':'spherical','generator':a.k,'characters':branches,'pseudo':None}

def write_json(path,data):
    path.write_text(json.dumps(data,indent=2)+'\n')

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--input',type=Path,default=ROOT.parent/'census/data/rings.jsonl')
    ap.add_argument('--output',type=Path,default=ROOT/'results')
    ap.add_argument('--models',type=Path,default=ROOT/'models.json')
    ap.add_argument('--workers',type=int,default=4)
    args=ap.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    rows=[json.loads(l) for l in args.input.open()];remaining=list(rows);certificates={};stages=[]
    begin=time.monotonic()
    def apply(label,test):
        nonlocal remaining
        start=time.monotonic();keep=[];excluded=0
        for row in remaining:
            c=test(row['tensor'])
            if c is None:keep.append(row)
            else:certificates[row['id']]={'stage':label,'certificate':c};excluded+=1
        remaining=keep
        stages.append({'filter':label,'excluded':excluded,'remaining':len(remaining),'seconds':round(time.monotonic()-start,6)})
        print(stages[-1],flush=True)
    apply('rank_two',rank_two)
    apply('formal_codegree_dnumber',rapid.dnumber)
    spherical_start=time.monotonic()
    # Arithmetic is run before the published-family classifications. The
    # central step may only be used after every surviving character orbit
    # has global dimension conjugate to the FP global dimension.
    start=time.monotonic();keep=[]
    with multiprocessing.Pool(max(1,args.workers)) as pool:
        arithmetic=dict(pool.imap_unordered(arithmetic_task,remaining))
    for row in remaining:
        c=arithmetic[row['id']]
        if c is None:keep.append(row)
        else:certificates[row['id']]={'stage':'spherical_arithmetic','certificate':c}
    excluded=len(remaining)-len(keep);remaining=keep
    stages.append({'filter':'spherical_arithmetic','excluded':excluded,'remaining':len(remaining),
                   'seconds':round(time.monotonic()-start,6)})
    print(stages[-1],flush=True)
    apply('published_rank_four_families',small_families)
    start=time.monotonic();left=[];source={row['id']:row for row in remaining}
    with multiprocessing.Pool(max(1,args.workers)) as pool:
        for index,c in pool.imap_unordered(spherical_task,remaining):
            if c is None:left.append(source[index])
            else:
                require(c['pseudo'] is not None,'central stage received arithmetic-only exclusion')
                certificates[index]={'stage':'central_induction','certificate':c}
    excluded=len(remaining)-len(left);remaining=sorted(left,key=lambda x:x['id'])
    stages.append({'filter':'central_induction','excluded':excluded,'remaining':len(remaining),
                   'seconds':round(time.monotonic()-start,6)})
    print(stages[-1],flush=True)
    spherical_seconds=round(time.monotonic()-spherical_start,6)
    models=json.loads(args.models.read_text());model_keys={canonical(x['matrices']):x['model'] for x in models}
    require(len(model_keys)==len(models),'duplicate models')
    survivors=[]
    for row in remaining:
        model=model_keys.get(canonical(row['tensor']))
        require(model is not None,'unresolved fusion ring '+str(row['id']))
        certificates[row['id']]={'stage':'model','certificate':{'kind':'model','model':model}}
        survivors.append({'id':row['id'],'tag':row['tag'],'parameters':row['parameters'],'model':model})
    require(len(survivors)==len(models),'missing advertised model')
    with (args.output/'certificates.jsonl').open('w') as out:
        for row in rows:
            record={'id':row['id'],'tag':row['tag'],'parameters':row['parameters'],**certificates[row['id']]}
            out.write(json.dumps(record,separators=(',',':'))+'\n')
    summary={'arithmetic_backend':rapid.BACKEND,'census_count':len(rows),'stages':stages,'model_count':len(survivors),'elapsed_seconds':round(time.monotonic()-begin,6),'workers':args.workers,'spherical_pipeline_seconds':spherical_seconds,'schema_version':5}
    write_json(args.output/'summary.json',summary);write_json(args.output/'survivors.json',survivors)
    print('COMPLETE',summary['elapsed_seconds'],'seconds;',len(survivors),'models',flush=True)

if __name__=='__main__':main()
