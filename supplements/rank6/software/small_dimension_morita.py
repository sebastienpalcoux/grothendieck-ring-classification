"""Tensor-based integral dimension-30/60 Morita and indicator obstructions.

Categorical inputs are stated in the manuscript. This checker certifies their
finite hypotheses; it does not purport to prove those theorems computationally.
No census identifier is accepted by certificate() or verify().
"""
import itertools
from functools import lru_cache
from exact import require


def closure(R, dual, generators):
    result = {0, *generators}
    while True:
        enlarged = result | {dual[i] for i in result}
        enlarged |= {k for i in result for j in result
                     for k, multiplicity in enumerate(R[i][j]) if multiplicity}
        if enlarged == result:
            return sorted(result)
        result = enlarged


def subrings(R, dual, dimensions):
    n = len(R)
    result = []
    for mask in range(1 << (n - 1)):
        basis = [0] + [i for i in range(1, n) if mask & (1 << (i - 1))]
        if closure(R, dual, basis) == basis:
            result.append({'basis': basis, 'dimension': sum(dimensions[i] ** 2 for i in basis)})
    return result


@lru_cache(maxsize=2)
def a5_audit(subgroup_order):
    """All group data are reconstructed from even permutations of five letters."""
    G = [p for p in itertools.permutations(range(5))
         if sum(p[i] > p[j] for i in range(5) for j in range(i + 1, 5)) % 2 == 0]
    index = {p: i for i, p in enumerate(G)}
    M = [[index[tuple(p[q[i]] for i in range(5))] for q in G] for p in G]
    n = len(G)
    require(n == 60 and G[0] == tuple(range(5)), 'A5 reconstruction')
    inverse = [next(j for j in range(n) if M[i][j] == 0) for i in range(n)]

    def generated(gens):
        H = {0}
        while True:
            new = H | {M[x][g] for x in H for g in gens}
            if new == H:
                return frozenset(H)
            H = new

    def order(x):
        v, k = x, 1
        while v != 0:
            v = M[v][x]
            k += 1
        return k

    orders = [order(i) for i in range(n)]
    require(subgroup_order in (6, 10), 'unsupported A5 subgroup order')
    prime = subgroup_order // 2
    r = index[(1, 2, 3, 4, 0) if prime == 5 else (1, 2, 0, 3, 4)]
    s = index[(0, 4, 3, 2, 1) if prime == 5 else (1, 0, 2, 4, 3)]
    H = generated([r, s])
    require(len(H) == subgroup_order and orders[r] == prime and orders[s] == 2, 'dihedral subgroup')
    require(M[M[s][r]][s] == inverse[r], 'dihedral relation')
    conjugates = {frozenset(M[M[x][a]][inverse[x]] for a in H) for x in range(n)}
    all_tens = {generated([x, y]) for x in range(n) if orders[x] == prime
                for y in range(n) if orders[y] == 2}
    all_tens = {K for K in all_tens if len(K) == subgroup_order}
    require(all_tens == conjugates and len(conjugates) == 60//subgroup_order, 'dihedral subgroups')
    # A group of order 2q, for q=3 or 5, without an element of order 2q
    # is dihedral and generated by orders q and two. This list is exhaustive.
    require(subgroup_order not in orders, 'unexpected cyclic even-order subgroup')
    commutators = [M[M[M[x][y]][inverse[x]]][inverse[y]]
                   for x in range(n) for y in range(n)]
    require(len(generated(commutators)) == 60, 'A5 not perfect')
    involutions = [x for x in range(n) if orders[x] == 2]
    involution_representative = next(x for x in H if orders[x] == 2)
    conjugacy_class = {M[M[x][involution_representative]][inverse[x]] for x in range(n)}
    require(conjugacy_class == set(involutions), 'involutions not conjugate into H')
    seen = set()
    cosets = []
    for g in range(n):
        if g in seen:
            continue
        coset = {M[g][h] for h in H}
        seen |= coset
        S = {h for h in H if M[M[inverse[g]][h]][g] in H}
        returns = sorted(x for x in coset if M[x][x] in S)
        if len(S) == 2:
            require(len(S) == len(returns) == 2, 'wrong involution-return count')
            require(all(orders[x] == 2 for x in returns), 'return is not an involution')
        cosets.append({'representative': g, 'stabilizer': sorted(S),
                       'returns': returns, 'return_orders': [orders[x] for x in returns]})
    covered = set(); sizes = []
    for g in range(n):
        if g in covered: continue
        double = {M[M[h][g]][k] for h in H for k in H}
        covered |= double; sizes.append(len(double))
    require(any(len(c['stabilizer']) == 2 for c in cosets), 'missing prime-dimensional double coset')
    return {'group_order': n, 'subgroup': sorted(H), 'element_orders': sorted(set(orders)),
            'dihedral_subgroup_order': subgroup_order, 'conjugate_subgroups': len(all_tens), 'involution_class_size': len(involutions),
            'commutator_subgroup_order': 60, 'double_coset_sizes': sizes,
            'right_cosets': cosets, 'target_simple_dimension': prime, 'target_second_indicator': 1}


def dimension_vectors(n, total):
    import math
    def tails(length, rest):
        if length == 0:
            if rest == 0: yield ()
            return
        for value in range(1, math.isqrt(rest-length+1)+1):
            for tail in tails(length-1, rest-value*value):
                yield (value,)+tail
    return [(1,)+t for t in tails(n-1,total-1)]


_DIMENSIONS = dimension_vectors(6,30)+dimension_vectors(6,60)


def structural_data(R):
    if len(R) != 6:
        return None
    for dimensions in _DIMENSIONS:
        if all(sum(a * dimensions[k] for k, a in enumerate(R[i][j]))
               == dimensions[i] * dimensions[j] for i in range(6) for j in range(6)):
            break
    else:
        return None
    dual = [next(j for j in range(6) if R[i][j][0]) for i in range(6)]
    invertibles = [i for i, d in enumerate(dimensions) if d == 1]
    adjoint = closure(R, dual, [k for i in range(6)
                               for k, a in enumerate(R[i][dual[i]]) if a])
    subs = subrings(R, dual, dimensions)
    return {'dimensions': list(dimensions), 'global_dimension': sum(d*d for d in dimensions),
            'duality': dual, 'invertibles': invertibles,
            'adjoint_basis': adjoint, 'subrings': subs}


def certificate(R):
    data = structural_data(R)
    if data is None:
        return None
    d, dual = data['dimensions'], data['duality']
    if data['global_dimension'] == 30:
        if max(d) <= 2: return None
        from oriented_signed import validate_general
        validate_general(R)
        return {'kind': 'small_dimension_morita', 'branch': 'dimension30', **data,
                'normal_cyclic_index': 2, 'cyclic_subgroup_order': 15,
                'allowed_simple_dimensions': [1, 2]}
    if data['adjoint_basis'] != list(range(6)) or len(data['invertibles']) != 2 or max(d) <= 4:
        return None
    spectrum = sorted({s['dimension'] for s in data['subrings']})
    if spectrum not in ([1, 2, 6, 60], [1, 2, 10, 60]): return None
    order = spectrum[2]
    prime = order//2
    targets = [i for i, value in enumerate(d) if value == prime]
    if not any(dual[i] != i for i in targets): return None
    from oriented_signed import validate_general
    validate_general(R)
    return {'kind': 'small_dimension_morita', 'branch': 'dimension60', **data,
            'solvable_quotient_dimension': 30, 'solvable_simple_dimension_bound': 4,
            'possible_A5_subgroup_order': order,
            'nonselfdual_witness': next(i for i in targets if dual[i] != i),
            'group_theoretical_indicator_audit': a5_audit(order)}


def verify(R, cert):
    require(cert.get('kind') == 'small_dimension_morita', 'wrong Morita certificate kind')
    reconstructed = certificate(R)
    require(reconstructed is not None, 'Morita obstruction hypotheses do not hold')
    require(cert == reconstructed, 'Morita certificate differs from exact reconstruction')
    return True


if __name__ == '__main__':
    import argparse, json, time
    from pathlib import Path
    root = Path(__file__).resolve().parents[1]
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--scan', action='store_true')
    ap.add_argument('--out', type=Path)
    args = ap.parse_args()
    start = time.monotonic()
    rows = json.loads((root/'data/census.json').read_text())
    matches, applicable = [], []
    for row in rows:
        data = structural_data(row['N'])
        if data is not None:
            applicable.append({'id': row['id'], 'multiplicity': row['m'], **data})
        c = certificate(row['N'])
        if c is not None:
            verify(row['N'], c)
            matches.append({'id': row['id'], 'status': 'excluded', 'certificate': c})
    report = {'census_size': len(rows), 'dimension_matches': applicable,
              'exclusions': matches, 'seconds': time.monotonic()-start}
    if args.out:
        if args.out.exists():
            raise SystemExit('Refusing to overwrite scan output')
        args.out.write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps({'scanned': len(rows), 'matches': [r['id'] for r in applicable],
                      'excluded': [r['id'] for r in matches], 'seconds': report['seconds']}, indent=2))
